static uint8_t search_rampup_table(uint16_t temperature)
{
	for( uint8_t i = 0; i < sizeof(rampup_t_e_table)/sizeof(rampup_t_e_table[0]); i++ )
	{
		if( temperature == rampup_t_e_table[i][0] )
			return i;
	}
	return 0;
}
