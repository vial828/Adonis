// callback each 20ms
void heat_monitor(HEATER* heater)
{
    FDB_area_b1_u* p_fdb_b_info = get_fdb_b_info_handle();
	uint16_t pv = (int16_t)((heater->CurrDetectTemp - (float)p_fdb_b_info->fdb_b1_t.tempAdjB/100.0f)/p_fdb_b_info->fdb_b1_t.tempAdjK);

	float power = 0;
	float shc = 0;

	if( heater->HeatingTime < 8000 )	
	{
		int16_t* ini_p = get_ini_val_info_handle();
		uint8_t start_temperature_idx = 0;

		if( rampup_energy == 0 )
		{
			start_temperature_idx = search_rampup_table(pv);
			
			//per the index calculate the average power output during rampup phase.
			rampup_energy = rampup_t_e_table[212][1] - rampup_t_e_table[start_temperature_idx][1];
			average_p = rampup_energy / 12.0 ;
			if(average_p * 2 >= ((float)ini_p[DB_FLT_TC_PWR_LIM]/100 + 1.0f) || average_p * 2  > (float)ini_p[DB_FLT_TC_PWR_LIM]/100)
			{
				full_power_t = 2 * rampup_energy * 1000 / (ini_p[DB_FLT_TC_PWR_LIM]/100) - 12000; // in ms
			}
			sm_log( SM_LOG_WARNING, "full_power_t = %d \r\n", full_power_t );
		}
		// output the rampup energy in liner from high to low, total energy output during the first 12s is allocated to each 20ms cycle
		if(ini_p[DB_FLT_TC_PWR_LIM] > 0) 
		{
			if( full_power_t > 0 )
			{
				if( heater->HeatingTime <= full_power_t )
					heater->SetPower = (float)ini_p[DB_FLT_TC_PWR_LIM]/100;
				else
					heater->SetPower = (float)ini_p[DB_FLT_TC_PWR_LIM]/100 * ( 1.0 - (float)(heater->HeatingTime - full_power_t)/ (12000 - full_power_t) ) ;	
			}
			else
			{
				heater->SetPower = average_p * 2 * (1 - (float)heater->HeatingTime / 12000.0 ); 
			}
		}
		if( pv > 240.0 )
			heater->SetPower = heater->SetPower > 2.5 ? 2.5 : heater->SetPower;

		shc = heater->SetPower * 100 / (pv - delta_t);

		for( uint8_t i = 0; i < 6; i++ )
		{
			w[i].J = heater->Heating_J;
		}

		fun_increase_pid_dumy( heater->CurrTargetTemp, pv );
	}
	else 
	{	// > 8s
		uint8_t is_exceeded = FALSE;
		uint16_t current_idx = heater->HeatingTime / 100 >= sizeof(base_J_ref)/sizeof(base_J_ref[0])? sizeof(base_J_ref)/sizeof(base_J_ref[0]) - 1 : heater->HeatingTime / 100;
		//SHC detection
		shc = heater->SetPower * 100 / (pv - delta_t);
		
		for( uint8_t i = 0; i < 6; i++ )
		{
			if( current_idx >= (w[i].count + 1) * (i+1) * 50 ) // window length = (i+1) * 5
			{
				if( heater->Heating_J - w[i].J > base_J_ref[current_idx] - base_J_ref[ current_idx - (i+1) * 50] )
				{
					is_exceeded = TRUE;
					sm_log( SM_LOG_WARNING, "w[%d] %ds exceeded. %.3f > %.3f \r\n", i, (i+1) * 50, heater->Heating_J - w[i].J, base_J_ref[current_idx] - base_J_ref[ current_idx - (i+1) * 50] );
				}
				w[i].J = heater->Heating_J;
				w[i].count++;
			}
		}

		if( is_exceeded )
		{
			target_delta_t += target_delta_t > 40? 0 : 5;
			delta_t_change_cycle = 400; // 8s 
			sm_log( SM_LOG_WARNING, "target_delta_t = %d \r\n", target_delta_t );
		}
		else if( shc < shc_thres )
		{
			high_shc_count = 0;
			if( pv < heater->CurrTargetTemp + 2  ) //todo: add scenario when stick is fired and temp. ramp up even with power 0
			{
				if( ++low_shc_count > 50 ) // continue to detect low shc more than 1s
				{
					low_shc_count = 0;
					target_delta_t += target_delta_t > 20? 0 : 5;
					delta_t_change_cycle = 400; // 8s 
					sm_log( SM_LOG_WARNING, "t: %d SHC %.3f. pv %d. target %d t_delta %d up\r\n", heater->HeatingTime, shc, pv, (uint16_t)heater->CurrTargetTemp, target_delta_t);
					if( target_delta_t >= 30) //stop heat
					{
						//set_system_status(IDLE);
						//sm_log( SM_LOG_WARNING, "t: %d SHC low timeout stop heat!!\r\n", heat.time );
					}
				}
			}
		}
		else if( pv > heater->CurrTargetTemp - 3 ) // only when temp. is close to target temp. the SHC is more stable to detect
		{
			low_shc_count = 0;
			if( ++high_shc_count > 50 ) // continue to detect high shc more than 1s
			{
				high_shc_count = 0;
				if( target_delta_t > 5 )
				{
					target_delta_t -= 5;
					delta_t_change_cycle = 400; // 8s
					sm_log( SM_LOG_WARNING, "t: %d SHC %.3f. pv %d. target %d t_delta %d down\r\n", heater->HeatingTime, shc, pv, (uint16_t)heater->CurrTargetTemp, target_delta_t);
				}
				else if( target_delta_t == 10 && shc > 1.6 )
				{
					//target_delta_t -= 10;
					//delta_t_change_cycle = 250; // 5s later check again
					//sm_log( SM_LOG_WARNING, "t: %d SHC %.3f. target delta down %d \r\n", heat.time, shc, target_delta_t);
				}
			}
		}

		if( delta_t_change_cycle > 0 && delta_t !=  (uint16_t)(target_delta_t * p_fdb_b_info->fdb_b1_t.tempAdjK + p_fdb_b_info->fdb_b1_t.tempAdjB/100.0f) )
		{
			//delta_t roll back to target value in step of 200ms, so roll back of a gap value 10 will need 2ses 
			if( delta_t_change_cycle % 10 == 0 )
			{
				delta_t += (uint16_t)(target_delta_t * p_fdb_b_info->fdb_b1_t.tempAdjK + p_fdb_b_info->fdb_b1_t.tempAdjB/100.0f) > delta_t ? 
				1 : ( (uint16_t)(target_delta_t * p_fdb_b_info->fdb_b1_t.tempAdjK + p_fdb_b_info->fdb_b1_t.tempAdjB/100.0f) == delta_t ? 0: -1 );

				if( delta_t ==  (uint16_t)(target_delta_t * p_fdb_b_info->fdb_b1_t.tempAdjK + p_fdb_b_info->fdb_b1_t.tempAdjB/100.0f) )
					sm_log( SM_LOG_WARNING, "delta_t = %d \r\n", delta_t);
			}
			delta_t_change_cycle--;
		}
	}
}


